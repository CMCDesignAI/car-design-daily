#!/usr/bin/env python3
"""Build tool/moods.js from tools/moods.txt (小工具 mood dictionary).
Adds Simplified-Chinese variants (opencc t2s, if installed), dedupes synonyms across groups (first wins), caps at 7 names/group."""
import os, re, json, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
try:
    import opencc; T2S = opencc.OpenCC("t2s").convert
except Exception:
    T2S = None; print("[gen_moods] opencc not installed: no Simplified variants added", file=sys.stderr)
groups, extra = [], []
for ln in open(f"{ROOT}/tools/moods.txt", encoding="utf-8"):
    ln = ln.strip()
    if not ln or ln.startswith("#"): continue
    if ln.startswith("="): extra.append(ln[1:].split("|")); continue
    names, vals = ln.rsplit(":", 1)
    v = [float(x) for x in vals.split(",")]; assert len(v) == 6, ln
    h, sp, s0, s1, l0, l1 = v; assert 0 <= h <= 360 and 0 <= s0 <= s1 <= 100 and 0 <= l0 <= l1 <= 100, ln
    groups.append([[n.strip() for n in names.split("|") if n.strip()], v])
byname = {n.lower(): g for g in groups for n in g[0]}
for e in extra:
    g = byname.get(e[0].lower()); assert g, f"unknown group {e[0]}"
    g[0] += e[1:]
seen, out, short = set(), [], []
for names, v in groups:
    ns = []
    for n in names + ([T2S(n) for n in names if re.search(r"[\u4e00-\u9fff]", n)] if T2S else []):
        k = n.lower()
        if k in seen or n in ns: continue
        seen.add(k); ns.append(n)
    ns = ns[:7]
    if not ns: continue
    if len(ns) < 3: short.append(ns)
    out.append("|".join(ns) + ":" + ",".join(f"{x:g}" for x in v))
js = "/* generated by tools/gen_moods.py from tools/moods.txt: name|synonyms:hue,hueSpread,sat0,sat1,light0,light1 */\nwindow.CDD_MOODS=" + json.dumps(";".join(out), ensure_ascii=False) + ";\n"
open(f"{ROOT}/tool/moods.js", "w", encoding="utf-8").write(js)
print(f"moods: {len(out)} groups, {sum(len(x.split(chr(58))[0].split(chr(124))) for x in out)} names; <3 names: {len(short)}", short)
